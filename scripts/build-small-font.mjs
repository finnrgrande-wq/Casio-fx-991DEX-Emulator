// ---------------------------------------------------------------- Ausgabe
const esc = (s) => {
  let o = '';
  for (const ch of s) {
    const cp = ch.codePointAt(0);
    if (ch === "'") o += "\\'";
    else if (ch === '\\') o += '\\\\';
    else if (cp >= 0x20 && cp < 0x7f) o += ch;
    else if (cp > 0xffff) o += `\\u{${cp.toString(16).toUpperCase()}}`;
    else o += `\\u${cp.toString(16).toUpperCase().padStart(4, '0')}`;
  }
  return `'${o}'`;
};

const seen = new Set();
let count = 0;
let ts = `import type { PixelFont } from '../types';

/**
 * Kleine Proportionalschrift (Klartext, Menüs, Statuszeile) für das 192×64-Punktraster.
 *
 * - Rasterhöhe 8 Zeilen: Großbuchstaben und Ziffern belegen Zeile 0–6 (Grundlinie = Zeile 6),
 *   Zeile 7 gehört nur den Unterlängen (g, j, p, q, y, Komma, Semikolon, Unterstrich).
 * - Kleinbuchstaben haben eine x-Höhe von 5 Zeilen (Zeile 2–6).
 * - Ziffern sind tabellarisch (alle 5 Punkte breit).
 * - Umlaut-Punkte sitzen in Zeile 0/1, die Buchstabenkörper darunter.
 *
 * Alle Glyphen sind eigene Zeichnungen. Diese Datei wird nicht von Hand gepflegt, sondern
 * ist ein übersichtliches Raster: '#' = Punkt an, '.' = Punkt aus.
 */
export const SMALL_FONT: PixelFont = {
  height: 8,
  baseline: 6,
  spacing: 1,
  glyphs: {
`;
const json = {};
for (const s of sections) {
  ts += `    // --- ${s.title} ---\n`;
  for (const gl of s.glyphs) {
    if (seen.has(gl.key)) throw new Error('Doppelt: ' + gl.key);
    seen.add(gl.key);
    count++;
    json[gl.key] = { w: gl.w, rows: gl.rows };
    const printable = gl.key.length === 1 && gl.key.codePointAt(0) >= 0x20 && gl.key.codePointAt(0) < 0x7f;
    const cm = printable ? '' : ` // ${gl.key}`;
    ts += `    ${esc(gl.key)}: { w: ${gl.w}, rows: [${cm}\n`;
    for (const r of gl.rows) ts += `      '${r}',\n`;
    ts += `    ] },\n`;
  }
}
ts += `  },\n};\n`;
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, ts, 'utf8');
console.log('Glyphen:', count);
