/** g(zeichen | [zeichen, alias...], startzeile, zeilen) */
function g(chars, start, rows) {
  const list = Array.isArray(chars) ? chars : [chars];
  const w = rows[0].length;
  for (const r of rows) {
    if (r.length !== w) throw new Error(`Breite ${JSON.stringify(list[0])}: "${r}" != ${w}`);
    if (!/^[#.]+$/.test(r)) throw new Error(`Ungueltige Zeichen in ${list[0]}: ${r}`);
  }
  const full = [];
  for (let i = 0; i < 8; i++) {
    const idx = i - start;
    full.push(idx >= 0 && idx < rows.length ? rows[idx] : '.'.repeat(w));
  }
  if (start + rows.length > 8) throw new Error(`Zu viele Zeilen: ${list[0]}`);
  for (const c of list) cur.glyphs.push({ key: c, w, rows: full });
}

